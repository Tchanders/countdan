<?php

$file = fopen( __DIR__ . '/brit-a-z.txt', 'r' );

$wordlist = array();

while( $line = fgets( $file ) ) {
	if( preg_match( '/^([a-z]{4,9})\n?\r?$/', $line, $matches ) ) {
		$word = $matches[1];
		$letters = str_split( $word );
		sort( $letters );
		$sortedletters = implode( '', $letters );
		if( !isset( $wordlist[$sortedletters] ) ) {
			$wordlist[$sortedletters] = array();
		}
		array_push( $wordlist[$sortedletters], $word );
	}
}

fclose( $file );

// Conundrums are common nine-letter words with only one anagram
$commonNines = file( __DIR__ . '/common-nines.txt', FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES );
$conundrums = array();
foreach ( $commonNines as $word ) {
	$letters = str_split( $word );
	sort( $letters );
	$sortedletters = implode( '', $letters );
	if ( isset( $wordlist[$sortedletters] ) && count( $wordlist[$sortedletters] ) === 1 ) {
		array_push( $conundrums, $word );
	}
}

$output = "// This file is generated by maintenance/build-letters.php. Do not edit directly.\n" .
	"// To regenerate, run `npm run build`.\n" .
	'var wordlist = ' . json_encode( $wordlist, JSON_PRETTY_PRINT ) . ";\n" .
	'var conundrums = ' . json_encode( $conundrums, JSON_PRETTY_PRINT ) . ';';

file_put_contents( __DIR__ . '/../js/letters.js', $output );
